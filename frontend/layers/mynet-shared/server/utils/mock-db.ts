const isoAgo = (minutesAgo: number) => new Date(Date.now() - minutesAgo * 60_000).toISOString()
const isoAhead = (daysAhead: number) => new Date(Date.now() + daysAhead * 86_400_000).toISOString()

let seqCounter = 900

export function nextMockId(prefix: string): string {
  seqCounter += 1
  return `${prefix}-${seqCounter}`
}

export function generateVoucherCode(planCode: string, n: number): string {
  const clean = planCode.replace(/[^A-Z0-9]/g, '').slice(0, 4).padEnd(4, 'X')
  const rand = ((n * 7919 + 104729) % 900000 + 100000).toString()
  return `MYNT-${clean}-${rand.slice(0, 4)}`
}

