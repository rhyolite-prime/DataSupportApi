export function recomputeBatchCounts(db: MyNetMockDatabase, batchId: string) {
  const batch = db.voucherBatches.find(b => b.id === batchId)
  if (!batch) return
  const rows = db.vouchers.filter(v => v.batchId === batchId)
  batch.quantity = rows.length
  batch.availableCount = rows.filter(v => v.status === 'AVAILABLE').length
  batch.assignedCount = rows.filter(v => v.status === 'ASSIGNED').length
  batch.soldCount = rows.filter(v => v.status === 'SOLD').length
  batch.redeemedCount = rows.filter(v => v.status === 'REDEEMED').length
  batch.voidCount = rows.filter(v => v.status === 'VOID').length
}

export function recomputeAgentStock(db: MyNetMockDatabase, agentId: string) {
  const agent = db.agents.find(a => a.id === agentId)
  if (!agent) return
  agent.vouchersInStock = db.vouchers.filter(v => v.agentId === agentId && v.status === 'ASSIGNED').length
}
